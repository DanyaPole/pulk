// Builds web/data.js from the Android sources of this repository, so the web version and the app say the same things:
// the star's letters, quick replies, situations, drills and the pond's milestones.
// node tools/build-web.js
const fs = require('fs'), path = require('path');
const src = path.join(__dirname, '..');
const kt = f => fs.readFileSync(path.join(src, 'app/src/main/java/app/pulk', f), 'utf8');
const strings = s => [...s.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map(m => m[1].replace(/\\"/g, '"').replace(/\\\\/g, '\\'));

const pulse = kt('Pulse.kt');
function table(name) {
  const body = pulse.match(new RegExp('private val ' + name + ' = arrayOf\\(([\\s\\S]*?)\\n    \\)'))[1];
  return [...body.matchAll(/arrayOf\(([^)]*)\)/g)].map(m => strings(m[1]));
}
const phrases = kt('Phrases.kt');
const quick = strings(phrases.match(/val QUICK = listOf\(([^)]*)\)/)[1]);
const situations = [...phrases.matchAll(/"([^"]+)" to listOf\(([\s\S]*?)\),?\n/g)].map(m => [m[1], strings(m[2])]);
const day = [...phrases.matchAll(/Triple\("([^"]+)", (\d+), listOf\(([\s\S]*?)\)\)/g)].map(m => [m[1], +m[2], strings(m[3])]);
const drillsSrc = kt('Drills.kt');
function themes(block) {
  return [...block.matchAll(/Theme\("([^"]+)", "([^"]+)", listOf\(([\s\S]*?)\n\s*\)\)/g)].map(m => ({
    title: m[1], about: m[2],
    tasks: [...m[3].matchAll(/Task\("([^"]+)", "([^"]+)", listOf\(([^)]*)\), listOf\(([^)]*)\)\)/g)].map(t => ({ scene: t[1], model: t[2], keys: strings(t[3]), choices: strings(t[4]) })),
  }));
}
const all = themes(drillsSrc);
const pond = [...kt('Pond.kt').matchAll(/Milestone\((\d+), "([^"]+)"\)/g)].map(m => [+m[1], m[2]]);
const jabWords = strings(kt('BubbleWords.kt').match(/val WORDS = listOf\(([\s\S]*?)\)/)[1]);
const replacement = Object.fromEntries([...kt('ReplacementBank.kt').matchAll(/const val (\w+) = ([\d.]+)/g)].map(m => [m[1], Number(m[2])]));
const completionSrc = kt('PhraseCompleter.kt');
const completion = Object.fromEntries([...completionSrc.matchAll(/const val (\w+) = (true|false|[\d.]+)/g)].map(m => [m[1], JSON.parse(m[2])]));
completion.QUESTION_MARKERS = strings(completionSrc.match(/val QUESTION_MARKERS = setOf\(([\s\S]*?)\)/)[1]);
const data = { RU: table('RU'), EN: table('EN'), SYM: table('SYM'), quick, situations, day, themes: all.filter(t => t.title !== 'Игра'), play: all.find(t => t.title === 'Игра'), pond, jabWords, replacement, completion };
const web = path.join(src, 'web');
fs.mkdirSync(web, { recursive: true });
fs.writeFileSync(path.join(web, 'data.js'), '// generated by tools/build-web.js from the Android sources — do not edit by hand\nwindow.PULK = ' + JSON.stringify(data) + ';\n');
// the same dictionaries as the Android app: one source of truth for suggestions on the phone and in the browser
for (const f of ['next_ru.txt', 'next_en.txt', 'dict_ru.txt', 'dict_en.txt']) fs.copyFileSync(path.join(src, 'app/src/main/assets', f), path.join(web, f));
console.log('RU petals', data.RU.length, 'quick', quick.length, 'situations', situations.length, 'day', day.length, 'themes', data.themes.length, 'play', !!data.play, 'pond', pond.length);
// Android uses the same child-safe filter as the web; edit web/stopwords.js, then regenerate.
const stopBox = { window: {} }; require('vm').runInNewContext(fs.readFileSync(path.join(web, 'stopwords.js'), 'utf8'), stopBox);
const stop = stopBox.window.PULK_STOP;
const arrays = ['words', 'roots', 'prefixes', 'parts'].map(k => '    private val ' + k + ' = setOf(' + stop[k].map(w => JSON.stringify(w.replace(/ё/g, 'е'))).join(', ') + ')').join('\n');
fs.writeFileSync(path.join(src, 'app/src/main/java/app/pulk/StopWords.kt'), `// generated by tools/build-web.js from web/stopwords.js — do not edit by hand
package app.pulk

object StopWords {
${arrays}
    fun bad(word: String): Boolean {
        val w = Words.fold(word.lowercase())
        return w in words || parts.any { it in w } || (listOf("") + prefixes).any { p ->
            w.startsWith(p) && roots.any { w.startsWith(it, p.length) }
        }
    }
}
`);
