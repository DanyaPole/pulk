package app.pulk

import android.app.Activity
import android.os.Bundle

/**
 * «Как помочь ребёнку»: most children start with a parent beside them; a minute of reading so the help helps.
 * The same advice as the web version's, with Android's own settings named.
 */
class ParentsActivity : Activity() {
    companion object {
        val SECTIONS = listOf(
            "Перед началом" to listOf(
                "Включите звук. Сядьте рядом, сбоку, а не напротив: так вы видите экран так же, как ребёнок.",
                "Телефон держит ребёнок или он лежит на столе. Палец — его.",
                "Пяти минут достаточно. Заканчивайте, пока ещё интересно."),
            "Как помогать" to listOf(
                "Покажите движение один раз своим пальцем над звездой — и уберите руку. Не водите его пальцем: тогда это сделал не он.",
                "Подождите 5–10 секунд, прежде чем подсказывать. Тишина — время подумать.",
                "Ошибок здесь нет. В уроке не та буква просто не печатается, а путь на звезде подсвечен. После трёх попыток Пульк поможет сам.",
                "Хвалите за попытку, коротко и спокойно: «Ты напечатал». Громкая похвала многим детям неприятна."),
            "Первый разговор" to listOf(
                "Начните с выбора: «Говорить» → «Предложить выбор». Спросите вслух и напишите «сок, вода». Ребёнок коснётся — телефон скажет.",
                "«Говорить» → «Фразы» → «Близким» — слова для вас: «Я тебя люблю», «Обними меня», «Посмотри!». Речь — это не только просьбы.",
                "«Разговор» — лента по очереди: вы можете написать вопрос, и ребёнок увидит его написанным."),
            "Когда ребёнок говорит" to listOf(
                "Отвечайте на сказанное как на настоящие слова. Сказал «нет» — это «нет»; уважайте его, когда это возможно.",
                "Не экзаменуйте («Напиши, что это»). Предлагайте настоящий выбор: «Сок или воду?»",
                "Говорите и сами через Пульк: напечатайте и скажите ребёнку что-нибудь — без требования повторить."),
            "Если что-то не так" to listOf(
                "Устал, расстроился, отворачивается — остановитесь. Капли в пруду не пропадают.",
                "Рука дрожит или задевает экран: «Для взрослого» → защита от случайных касаний; на главном экране — «Под мою руку».",
                "Голос звучит плохо: Настройки → Специальные возможности → Синтез речи — выберите русский язык и скачайте голос.",
                "Чтобы ребёнок не выходил из Пулька: Настройки → Безопасность → Закрепление приложений, потом закрепите «Говорить»."),
            "Что дальше" to listOf(
                "Урок → «Тренировки» по ситуациям → «Говорить» в жизни. Каждый получившийся шаг урока или тренировки — капля в пруду.",
                "Всё набранное остаётся на этом телефоне: у Пулька нет доступа к интернету."),
        )
    }

    override fun onCreate(b: Bundle?) {
        super.onCreate(b)
        val ui = Ui(this)
        val body = ui.column()
        body.addView(ui.title("Как помочь ребёнку"))
        body.addView(ui.note("Пульк — способ говорить: ребёнок печатает одним пальцем, телефон произносит. Заранее ничего знать не нужно."))
        for ((h, tips) in SECTIONS) { body.addView(ui.h(h)); for (t in tips) body.addView(ui.text("•  $t")) }
        val bottom = ui.bottomBar()
        bottom.addView(ui.button("Понятно", main = true) { finish() })
        setContentView(ui.screen(body, bottom))
    }
}
