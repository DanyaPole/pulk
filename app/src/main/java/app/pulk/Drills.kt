    private fun norm(s: String) = s.lowercase().replace('ё', 'е')

    /** The answer is about the scene: it has one of its word stems (any form, any order). */
    fun fits(answer: String, task: Task): Boolean {
        val a = norm(answer)
        if (task.keys.isEmpty()) return answer.isNotBlank()   // play: any answer is the answer
        return task.keys.any { a.contains(norm(it)) } || Lessons.closeEnough(answer, task.model)
    }
